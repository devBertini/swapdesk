#!/usr/bin/env python
"""Writes THIRD-PARTY-LICENSES.md: the third-party crates linked into the shipped Swapdesk binaries.

Standard library only. Usage (from anywhere):

    python scripts/third_party_licenses.py          # rewrite THIRD-PARTY-LICENSES.md
    python scripts/third_party_licenses.py --check  # exit 1 when the committed file is stale

The crate set is the union, over the Windows and macOS targets, of the normal dependencies (no dev and no build edges)
reachable from the workspace crates, as `cargo metadata --locked --filter-platform <target>` resolves them. A
build-only helper such as `cc` is not shipped; C code built by a -sys crate is, and its sources sit in that crate's
folder, so license files up to one folder below a -sys crate (or a crate with `links`) are read as well.
"""
import json
import os
import re
import subprocess
import sys

TARGETS = ("x86_64-pc-windows-msvc", "aarch64-apple-darwin")
LICENSE_NAME = re.compile(r"^(LICENSE|LICENCE|COPYING|NOTICE|UNLICENSE)([-_.].*)?$", re.IGNORECASE)
OUTPUT_NAME = "THIRD-PARTY-LICENSES.md"
NO_TEXT = "No license text was shipped in the crate's source; the SPDX expression above is the license."


def normalize_text(text):
    """LF line ends, no trailing spaces, one final newline (so equal texts compare equal)."""
    lines = [line.rstrip() for line in text.replace("\r\n", "\n").replace("\r", "\n").split("\n")]
    return "\n".join(lines).strip("\n") + "\n"


def reachable_ids(metadata):
    """Ids of the non-workspace packages reachable from the workspace members through normal edges."""
    members = set(metadata["workspace_members"])
    nodes = {n["id"]: n for n in metadata["resolve"]["nodes"]}
    seen = set()
    stack = list(members)
    visited = set()
    while stack:
        pid = stack.pop()
        if pid in visited:
            continue
        visited.add(pid)
        for dep in nodes.get(pid, {}).get("deps", []):
            if any(k.get("kind") is None for k in dep.get("dep_kinds", [])):
                stack.append(dep["pkg"])
                if dep["pkg"] not in members:
                    seen.add(dep["pkg"])
    return seen


def license_file_names(directory, listing):
    """Sorted license-looking file names of `listing` (a list of (name, is_file))."""
    return sorted(name for name, is_file in listing if is_file and LICENSE_NAME.match(name))


def find_license_files(crate_dir, deep):
    """[(relative path with '/', normalized text)] for a crate folder; `deep` also looks one folder below."""
    found = []

    def scan(directory, prefix):
        entries = sorted(os.listdir(directory))
        listing = [(n, os.path.isfile(os.path.join(directory, n))) for n in entries]
        for name in license_file_names(directory, listing):
            with open(os.path.join(directory, name), "r", encoding="utf-8", errors="replace", newline="") as f:
                found.append((prefix + name, normalize_text(f.read())))

    scan(crate_dir, "")
    if deep:
        for name in sorted(os.listdir(crate_dir)):
            sub = os.path.join(crate_dir, name)
            if os.path.isdir(sub) and name not in ("target", ".git"):
                scan(sub, name + "/")
    return found


def dedup_texts(crates):
    """crates: [{'files': [(path, text)]}]. Returns (texts, per-crate lists of (path, text index)), texts sorted."""
    texts = sorted({text for c in crates for _, text in c["files"]})
    index = {t: i for i, t in enumerate(texts)}
    return texts, [[(p, index[t]) for p, t in c["files"]] for c in crates]


def render(crates):
    """crates: [{'name','version','license','repository','files'}] in any order. Returns the document text."""
    crates = sorted(crates, key=lambda c: (c["name"], c["version"]))
    texts, refs = dedup_texts(crates)
    out = [
        "# Third-party licenses",
        "",
        "Swapdesk is licensed MIT OR Apache-2.0 (see `LICENSE-MIT` and `LICENSE-APACHE`). It links the third-party",
        "crates below, for Windows and macOS. Each section gives the crate, its license expression and its",
        "repository; the license texts found in each crate's source follow in the last part, once per distinct text.",
        "Generated by `scripts/third_party_licenses.py` from `Cargo.lock`; do not edit by hand.",
        "",
        f"{len(crates)} crates.",
        "",
        "## Crates",
        "",
    ]
    for crate, ref in zip(crates, refs):
        out.append(f"### {crate['name']} {crate['version']}")
        out.append("")
        out.append(f"- License: {crate['license'] or 'not declared in the manifest'}")
        out.append(f"- Repository: {crate['repository'] or 'none declared'}")
        if ref:
            out.append("- License texts: " + ", ".join(f"`{p}` (text {i + 1})" for p, i in ref))
        else:
            out.append(f"- License texts: {NO_TEXT}")
        out.append("")
    out.append("## License texts")
    out.append("")
    for i, text in enumerate(texts):
        users = sorted({f"{c['name']} {c['version']}" for c, r in zip(crates, refs) if any(j == i for _, j in r)})
        out.append(f"### Text {i + 1}")
        out.append("")
        out.append("Used by: " + ", ".join(users))
        out.append("")
        out.append("````text")
        out.append(text.rstrip("\n"))
        out.append("````")
        out.append("")
    return "\n".join(out)


def cargo_metadata(root, target):
    cmd = ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target]
    done = subprocess.run(cmd, cwd=root, capture_output=True, text=True, encoding="utf-8")
    if done.returncode != 0:
        sys.stderr.write(done.stderr)
        raise SystemExit(f"cargo metadata failed for {target}")
    return json.loads(done.stdout)


def collect(root):
    packages = {}
    ids = set()
    for target in TARGETS:
        meta = cargo_metadata(root, target)
        ids |= reachable_ids(meta)
        for p in meta["packages"]:
            packages[p["id"]] = p
    crates = []
    for pid in sorted(ids):
        p = packages[pid]
        directory = os.path.dirname(p["manifest_path"])
        deep = p["name"].endswith("-sys") or bool(p.get("links"))
        crates.append(
            {
                "name": p["name"],
                "version": p["version"],
                "license": p.get("license"),
                "repository": p.get("repository"),
                "files": find_license_files(directory, deep),
            }
        )
    return crates


def main(argv):
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    check = "--check" in argv
    crates = collect(root)
    document = render(crates)
    path = os.path.join(root, OUTPUT_NAME)
    if check:
        try:
            with open(path, "r", encoding="utf-8", newline="") as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current != document:
            sys.stderr.write(f"{OUTPUT_NAME} is stale: run python scripts/third_party_licenses.py\n")
            return 1
        print(f"{OUTPUT_NAME} is up to date ({len(crates)} crates)")
        return 0
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(document)
    without = [f"{c['name']} {c['version']}" for c in crates if not c["files"]]
    print(f"wrote {OUTPUT_NAME}: {len(crates)} crates, {len(without)} without license text")
    for name in without:
        print(f"  no text: {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
